CREATE FUNCTION pg_temp.ordinary_auth_role()
RETURNS kovcheg.auth_account_role
LANGUAGE sql
STABLE
AS $$
  SELECT role
  FROM pg_catalog.unnest(pg_catalog.enum_range(NULL::kovcheg.auth_account_role)) AS role
  WHERE role <> 'administrator'
  LIMIT 1;
$$;

